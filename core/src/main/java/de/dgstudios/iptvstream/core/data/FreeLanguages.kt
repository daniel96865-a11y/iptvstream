/** Eine Sprache, für die iptv-org eine Senderliste hat (languages/<code>.m3u). */
data class FreeLang(val code: String, val english: String) {
    /** Deutscher Name, wenn Android ihn kennt, sonst der englische. */
    val label: String by lazy { computeLabel() }

    private fun computeLabel(): String {
        GERMAN_NAMES[code]?.let { return it }
        val loc = java.util.Locale.forLanguageTag(code)
        val de = try { loc.getDisplayLanguage(java.util.Locale.GERMAN) } catch (_: Exception) { "" }
        return if (de.isBlank() || de.equals(code, ignoreCase = true)) english else de
    }
}

